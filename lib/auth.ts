/** Environment variables that may hold each user's password, in priority order. */
export const PASSWORD_ENV: Record<string, string[]> = {
  stille: ['STILLE_PASSWORD', 'SELLER_PASSWORD'],
  affe: ['AFFE_PASSWORD', 'MANAGER_PASSWORD'],
  fredland: ['FREDLAND_PASSWORD'],
  kvist: ['KVIST_PASSWORD'],
};

export function passwordFor(username: string): string | undefined {
  const keys = PASSWORD_ENV[username];
  if (!keys) return undefined;
  for (const key of keys) {
    const value = (process.env[key] || '').trim();
    if (value) return value;
  }
  return undefined;
}

/**
 * Passwords are stored only in server-side Vercel Secrets. Accepted formats:
 *   1. scrypt:N:r:p:saltHex:hashHex   (recommended — generated by scripts/hash-password.mjs;
 *                                      no "$" so .env.local files are never mangled by dotenv expansion)
 *   2. scrypt$N$r$p$saltHex$hashHex   (legacy spelling of the same hash)
 *   3. plaintext                      (constant-time compared, kept for migration convenience)
 */
export function verifyPassword(plain: string, stored: string | undefined): boolean {
  if (!stored) return false;
  const isScrypt = stored.startsWith('scrypt:') || stored.startsWith('scrypt$');
  if (isScrypt) {
    const parts = stored.split(/[:$]/);
    if (parts.length !== 6) return false;
    const [, n, r, p, saltHex, hashHex] = parts;
    try {
      const salt = Buffer.from(saltHex, 'hex');
      const expected = Buffer.from(hashHex, 'hex');
      // Reject truncated/garbled hashes: an empty buffer would otherwise compare equal to anything.
      if (salt.length < 8 || expected.length < 32) return false;
      if (plain.length > 512) return false;
      const actual = scryptSync(plain, salt, expected.length, {
        N: Number(n),
        r: Number(r),
        p: Number(p),
        maxmem: 64 * 1024 * 1024,
      });
      return actual.length === expected.length && timingSafeEqual(actual, expected);
    } catch {
      return false;
    }
  }
  const a = createHash('sha256').update(plain, 'utf8').digest();
  const b = createHash('sha256').update(stored, 'utf8').digest();
  return timingSafeEqual(a, b);
}

export function hashPassword(plain: string): string {
  const salt = createHash('sha256').update(`${Date.now()}:${Math.random()}`).digest().subarray(0, 16);
  const hash = scryptSync(plain, salt, 64, { N: 16384, r: 8, p: 1, maxmem: 64 * 1024 * 1024 });
  return `scrypt:16384:8:1:${salt.toString('hex')}:${hash.toString('hex')}`;
}

export async function createSessionValue(username: string, role: Role): Promise<string> {
  return signSession({ u: username, r: role, e: Date.now() + SESSION_TTL_MS });
}

export type SessionUser = { username: string; role: Role };

/** Trust only the headers the middleware injects after verifying the cookie. */
export function sessionFromRequest(req: Request): SessionUser | null {
  const username = req.headers.get('x-user') || '';
  const role = req.headers.get('x-role') || '';
  if (!username || (role !== 'seller' && role !== 'manager')) return null;
  return { username, role };
}

export async function resolveUser(username: string): Promise<{ username: string; display_name: string; role: Role } | null> {
  const user = await getUser(username);
  return user ? { username: user.username, display_name: user.display_name, role: user.role } : null;
}

/* ------------------------------------------------------------------ *
 * Brute-force protection (in-memory; best effort per serverless instance)
 * ------------------------------------------------------------------ */
type Attempt = { count: number; resetAt: number };
const attempts = new Map<string, Attempt>();
const MAX_ATTEMPTS = 6;
const WINDOW_MS = 10 * 60 * 1000;

function keyFor(ip: string, username: string) {
  return `${ip}::${username.toLowerCase()}`;
}

export function loginBlocked(ip: string, username: string): { blocked: boolean; retryAfter?: number } {
  const now = Date.now();
  const entry = attempts.get(keyFor(ip, username));
  if (!entry || entry.resetAt <= now) return { blocked: false };
  if (entry.count >= MAX_ATTEMPTS) {
    return { blocked: true, retryAfter: Math.ceil((entry.resetAt - now) / 1000) };
  }
  return { blocked: false };
}

export function recordLoginFailure(ip: string, username: string) {
  const now = Date.now();
  const key = keyFor(ip, username);
  const entry = attempts.get(key);
  if (!entry || entry.resetAt <= now) attempts.set(key, { count: 1, resetAt: now + WINDOW_MS });
  else entry.count += 1;
}

export function clearLoginFailures(ip: string, username: string) {
  attempts.delete(keyFor(ip, username));
}

export function clientIp(req: Request): string {
  const forwarded = req.headers.get('x-forwarded-for') || '';
  return forwarded.split(',')[0].trim() || req.headers.get('x-real-ip') || 'unknown';
}
